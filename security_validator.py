
import re


def validate_findings(findings, source_files):
    """
    Validate security findings generated by CodeShield AI.

    Features:
    - Verify source files and line numbers
    - Filter unsupported AI security claims
    - Reduce false positives for credentials
    - Check SQL injection evidence
    - Preserve legitimate ownership checks
    - Capture surrounding source code
    - Remove exact duplicate findings
    - Always return a list
    """

    if not isinstance(findings, list):
        return []

    if not isinstance(source_files, list):
        return []

    validated = []
    seen = set()

    # --------------------------------------------------
    # 1. BUILD SOURCE CODE LOOKUP
    # --------------------------------------------------

    source_lookup = {}

    for item in source_files:
        if not isinstance(item, dict):
            continue

        filename = item.get("filename", "")
        code = item.get("code", "")

        if isinstance(filename, str) and isinstance(code, str):
            source_lookup[filename] = code.splitlines()

    # --------------------------------------------------
    # 2. HELPER FUNCTIONS
    # --------------------------------------------------

    def is_environment_access(text):
        """Detect common environment-variable references."""

        return bool(
            re.search(
                r"Deno\.env\.get\s*\("
                r"|process\.env\."
                r"|os\.getenv\s*\("
                r"|os\.environ"
                r"|import\.meta\.env\.",
                text,
                re.IGNORECASE,
            )
        )

    def is_placeholder(text):
        """Identify clearly labeled demonstration secrets."""

        markers = [
            "NOT_REAL",
            "FAKE_KEY",
            "DUMMY_KEY",
            "EXAMPLE_KEY",
            "PLACEHOLDER",
            "YOUR_API_KEY",
            "YOUR_SECRET",
            "CHANGE_ME",
        ]

        upper_text = text.upper()

        return any(marker in upper_text for marker in markers)

    def is_credential_claim(name, description):
        combined = name + " " + description

        return any(
            term in combined
            for term in [
                "hardcoded",
                "hard-coded",
                "exposed secret",
                "exposed credential",
                "secret leakage",
                "credential leakage",
                "api key exposure",
                "service role key is directly exposed",
                "service-role key is directly exposed",
            ]
        )

    def is_unsupported_service_role_claim(
        name, description, actual_line, context
    ):
        """
        Reject AI findings that treat environment-variable
        access alone as proof of a leaked Supabase key.
        """

        combined = name + " " + description

        mentions_service_role = any(
            term in combined
            for term in [
                "service-role",
                "service role",
                "supabase_service_role_key",
            ]
        )

        claims_secret_exposure = any(
            term in combined
            for term in [
                "directly exposed",
                "hardcoded",
                "hard-coded",
                "secret exposed",
                "key exposed",
                "exposed in the code",
                "exposed in source",
                "exposed in the source",
            ]
        )

        if not (mentions_service_role and claims_secret_exposure):
            return False

        if not is_environment_access(actual_line):
            return False

        # Do not discard a finding when the surrounding
        # source actually contains a credential-like literal.
        literal_secret = re.search(
            r"""(?:service_role_key|api_key|secret|password)"""
            r"""\s*[:=]\s*["'][A-Za-z0-9_\-]{16,}["']""",
            context,
            re.IGNORECASE,
        )

        return literal_secret is None

    def has_sql_interpolation(context):
        """
        Detect SQL template literals containing interpolation.

        This is a heuristic, not proof of exploitability.
        """

        template_pattern = re.compile(
            r"`[^`]*\b(?:SELECT|INSERT|UPDATE|DELETE)\b"
            r"[^`]*\$\{[^}]+\}[^`]*`",
            re.IGNORECASE | re.DOTALL,
        )

        return bool(template_pattern.search(context))

    def has_sql_concatenation(context):
        """
        Detect simple SQL string concatenation patterns.
        """

        return bool(
            re.search(
                r"""(?:SELECT|INSERT|UPDATE|DELETE)\b"""
                r"""[^;\n]*["']\s*\+\s*[A-Za-z_$]""",
                context,
                re.IGNORECASE,
            )
        )

    def uses_supabase_query_builder(context):
        return bool(
            re.search(
                r"\.(?:eq|neq|gt|gte|lt|lte|in|"
                r"like|ilike|select|filter)\s*\(",
                context,
                re.IGNORECASE,
            )
        )

    # --------------------------------------------------
    # 3. VALIDATE EACH FINDING
    # --------------------------------------------------

    for finding in findings:

        if not isinstance(finding, dict):
            continue

        filename = finding.get("File", "")

        if filename not in source_lookup:
            continue

        try:
            line_number = int(finding.get("Line", 0))
        except (TypeError, ValueError):
            continue

        lines = source_lookup[filename]

        if not 1 <= line_number <= len(lines):
            continue

        actual_line = lines[line_number - 1].strip()

        name = str(
            finding.get("Vulnerability", "")
        ).lower()

        description = str(
            finding.get("Description", "")
        ).lower()

        detection = str(
            finding.get("Detection", "")
        )

        severity = str(
            finding.get("Severity", "Medium")
        ).capitalize()

        if severity not in {
            "Critical", "High", "Medium", "Low"
        }:
            severity = "Medium"

        # Five lines before and after the finding.
        context_start = max(0, line_number - 6)
        context_end = min(len(lines), line_number + 5)

        context = "\n".join(
            lines[context_start:context_end]
        )

        # --------------------------------------------------
        # 4. FILTER UNSUPPORTED CREDENTIAL CLAIMS
        # --------------------------------------------------

        if is_credential_claim(name, description):

            if is_placeholder(actual_line):
                continue

            if actual_line in {
                "}",
                "},",
                ");",
                "};",
                "]",
                "],",
            }:
                continue

            # Environment-variable access is not proof
            # that a secret is hardcoded or leaked.
            if is_environment_access(actual_line):

                # Filter only when the finding is about
                # exposure, not missing authorization.
                exposure_terms = [
                    "hardcoded",
                    "hard-coded",
                    "exposed",
                    "leak",
                ]

                if any(
                    term in (name + " " + description)
                    for term in exposure_terms
                ):
                    continue

        # --------------------------------------------------
        # 5. FILTER FALSE SUPABASE SERVICE-ROLE CLAIMS
        # --------------------------------------------------

        if detection == "AI Analysis":

            if is_unsupported_service_role_claim(
                name,
                description,
                actual_line,
                context,
            ):
                continue

        # --------------------------------------------------
        # 6. CHECK SQL INJECTION EVIDENCE
        # --------------------------------------------------

        if "sql injection" in name:

            # Expand the context to capture a multi-line
            # SQL template or concatenation.
            sql_start = max(0, line_number - 15)
            sql_end = min(len(lines), line_number + 15)

            sql_context = "\n".join(
                lines[sql_start:sql_end]
            )

            interpolated_sql = has_sql_interpolation(
                sql_context
            )

            concatenated_sql = has_sql_concatenation(
                sql_context
            )

            query_builder = uses_supabase_query_builder(
                sql_context
            )

            if (
                not interpolated_sql
                and not concatenated_sql
            ):
                # A SELECT statement alone does not
                # establish SQL injection.
                continue

            if (
                query_builder
                and not interpolated_sql
                and not concatenated_sql
                and detection == "AI Analysis"
            ):
                continue

        # --------------------------------------------------
        # 7. FILTER FALSE OWNERSHIP CLAIMS
        # --------------------------------------------------

        if any(
            term in name
            for term in [
                "access control",
                "authorization",
                "privilege escalation",
            ]
        ):

            standard_ownership_check = re.search(
                r"(?:owner_id|author_id)"
                r"\s*=\s*auth\.uid\(\)",
                actual_line,
                re.IGNORECASE,
            )

            if standard_ownership_check:
                continue

        # --------------------------------------------------
        # 8. GROUP FINDING TYPES
        # --------------------------------------------------

        issue_group = name

        if (
            "xss" in name
            or "cross-site scripting" in name
        ):
            issue_group = "xss"

        elif "sql injection" in name:
            issue_group = "sql_injection"

        elif (
            "hardcoded" in name
            or "credential" in name
        ):
            issue_group = "hardcoded_secret"

        elif (
            "missing authentication" in name
            or "broken authentication" in name
        ):
            issue_group = "authentication"

        elif (
            "access control" in name
            or "authorization" in name
        ):
            issue_group = "authorization"

        elif (
            "rls" in name
            or "row level security" in name
            or "row-level security" in name
        ):
            issue_group = "rls_policy"

        # --------------------------------------------------
        # 9. REMOVE EXACT DUPLICATES
        # --------------------------------------------------

        duplicate_key = (
            filename,
            line_number,
            issue_group,
        )

        if duplicate_key in seen:
            continue

        seen.add(duplicate_key)

        # --------------------------------------------------
        # 10. CAPTURE SOURCE CODE EVIDENCE
        # --------------------------------------------------

        evidence_lines = []

        for index in range(
            context_start,
            context_end,
        ):
            marker = (
                ">>"
                if index + 1 == line_number
                else "  "
            )

            evidence_lines.append(
                f"{marker} {index + 1:4d} | "
                f"{lines[index]}"
            )

        code_context = "\n".join(
            evidence_lines
        )

        # --------------------------------------------------
        # 11. SAVE VALIDATED FINDING
        # --------------------------------------------------

        updated = finding.copy()

        updated["Line"] = line_number
        updated["Severity"] = severity
        updated["Evidence"] = actual_line[:180]
        updated["CodeContext"] = code_context

        # All findings remain unconfirmed until
        # reviewed by a security professional.
        updated["VerificationStatus"] = (
            "Requires Manual Verification"
        )

        validated.append(updated)

    return validated
